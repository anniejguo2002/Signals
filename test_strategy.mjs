import assert from 'node:assert/strict';
import {simulate,neutral,rank} from '../frontend/src/strategy.ts';
const points=[{price:50,value:50},{price:70,value:70},{price:30,value:40}];
let result=simulate(points,0,neutral);
assert.ok(result.every(r=>r.delta===0));
assert.equal(rank([50,50,40],0),1);
assert.equal(rank([50,50,40],2),3);
result=simulate(points,0,{...neutral,priceChange:-20});
assert.equal(result[0].after.price,40);
assert.equal(result[0].delta,5);
assert.equal(result[1].delta,0);
result=simulate(points,0,{...neutral,launchLift:20,priceWeight:100});
assert.equal(result[0].delta,0);
result=simulate(points,0,{...neutral,response:20});
assert.equal(result[0].delta,0);
assert.ok(result[1].delta>0 && result[2].delta>0);
result=simulate([{price:100,value:90}],0,{priceChange:50,launchLift:40,response:0,priceWeight:50});
assert.deepEqual(result[0].after,{price:100,value:100});
assert.deepEqual(points,[{price:50,value:50},{price:70,value:70},{price:30,value:40}]);
console.log('PASS: neutral moves, tied ranks, pricing sensitivity, buyer weighting, competitor response, bounds, and immutable inputs.');
const {launchImpact,defaultPlan}=await import('../frontend/src/launch.ts');
assert.equal(launchImpact(defaultPlan).lift,0);
const launch={...defaultPlan,selected:['sso'],segment:'enterprise',adoption:100,readiness:100,budget:5};
assert.equal(launchImpact(launch).lift,9);
assert.equal(launchImpact({...launch,budget:2.5}).lift,4.5);
assert.equal(launchImpact({...launch,adoption:0}).lift,0);
assert.equal(launchImpact({...launch,readiness:0}).lift,0);
assert.ok(launchImpact({...launch,segment:'startup'}).lift<launchImpact(launch).lift);
assert.equal(launchImpact({...launch,points:{sso:12},weeks:{sso:10}}).lift,6);
console.log('PASS: feature selection, segment fit, capacity constraints, adoption, readiness, and custom estimates.');
